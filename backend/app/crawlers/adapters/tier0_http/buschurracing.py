BUSCHUR_BASE = "https://buschursllc.com"
CART_ROOT = BUSCHUR_BASE + "/br-cart/"

# Product URL path shape on PrestaShop: /br-cart/<category-slug>/<id>-<slug>.html
# Category URL path shape:              /br-cart/<id>-<category-slug>
_PRODUCT_PATH_RE = re.compile(r"^/br-cart/[a-z0-9][a-z0-9\-]*/\d+-[a-z0-9][^/]*\.html$", re.IGNORECASE)
_CATEGORY_PATH_RE = re.compile(r"^/br-cart/\d+-[a-z0-9][a-z0-9\-]*/?$", re.IGNORECASE)

# House-brand canonical form and detection patterns. The storefront signs
# products as ``Buschur's ...`` (apostrophe-s) and ``Buschur Racing`` in
# marketing. We canonicalize to ``"Buschur Racing"`` so the manufacturer list
# matches the brand as commonly written.
_HOUSE_BRAND = "Buschur Racing"
_HOUSE_BRAND_TITLE_RE = re.compile(r"^\s*buschur['']?s?\b", re.IGNORECASE)

DEFAULT_START_URLS = [
    # Third-party resale (JE forged pistons) — exercises the pass-through path.
    "https://buschursllc.com/br-cart/pistons-rings/95-je-forged-pistons-101.html",
    # House-brand exhaust — exercises the "Buschur Racing" house-brand coercion.
    "https://buschursllc.com/br-cart/home/2055-buschur-s-1g-dsm-turbo-back-exhaust.html",
]

# Tokens the title heuristic may pick on an Evo / DSM specialist that are
# actually the target vehicle / chassis / engine, not a part manufacturer.
# Dropped to ``None`` so the storefront doesn't grow a ``"Mitsubishi"`` or
# ``"Evo"`` manufacturer row next to real brands. Per-task blocklist.
_TITLE_NON_BRAND_TOKENS = frozenset(
    {
        # Mitsubishi-family / Evo / DSM
        "mitsubishi",
        "mitsu",
        "evo",
        "evolution",
        "lancer",
        "eclipse",
        "ralliart",
        "galant",
        "dsm",
        "1g",
        "2g",
        # Other makes that could appear on cross-platform kits
        "ford",
        "maverick",  # 22+ Ford Maverick line Buschur covers
        "subaru",
        "honda",
        "toyota",
        "nissan",
        "mazda",
        "chevrolet",
        "chevy",
        "evox",
        "evo-x",
        "evoxi",
        # Generic leaders that slip past the shared generic-word set
        "oem",
        "stock",
        "replacement",
        "universal",
    }
)

# SKU-suffix → manufacturer hints. The storefront tags third-party SKUs with
# a short brand code (``-JE`` = JE Pistons, ``-WIS`` = Wiseco). Kept tiny on
# purpose: the suffix is ambiguous (``-JE`` could be a part-code tail), so we
# only upgrade a missing brand — we never override a heuristic-derived one.
_SKU_SUFFIX_BRAND = {
    "JE": "JE Pistons",
    "WIS": "Wiseco",
    "WIS.": "Wiseco",
    "TIAL": "Tial",
    "ARP": "ARP",
}


def _brand_from_sku_suffix(sku: Optional[str]) -> Optional[str]:
    """Return the mapped manufacturer for a ``<prefix>-<SUFFIX>`` SKU shape, else None."""
    if not sku:
        return None
    parts = sku.rsplit("-", 1)
    if len(parts) != 2:
        return None
    suffix = parts[1].strip().upper()
    if not suffix:
        return None
    return _SKU_SUFFIX_BRAND.get(suffix)


def _normalize_part_manufacturer(part_manufacturer: Optional[str]) -> Optional[str]:
    """
    Drop car-make / chassis / platform tokens the title heuristic may pick on
    a Mitsubishi-DSM specialist. Third-party vendor strings (``"JE"``,
    ``"Wiseco"``, ``"Tial"``, ``"AEM"``, …) pass through unchanged so
    re-sold hardware lands on the real manufacturer.
    """
    if not part_manufacturer:
        return part_manufacturer
    brand = part_manufacturer.strip()
    if not brand:
        return None
    if brand.lower() in _TITLE_NON_BRAND_TOKENS:
        return None
    return brand


def _resolve_start_urls() -> List[str]:
    """Env override wins; otherwise discover via homepage category walk, then default."""
    raw = os.environ.get("CRAWLER_BUSCHURRACING_START_URLS", "").strip()
    if raw:
        return [u.strip() for u in raw.split(",") if u.strip()]
    urls = _discover_product_urls_via_categories()
    return urls if urls else list(DEFAULT_START_URLS)


def _is_product_url(url: str) -> bool:
    """True if ``url`` is a Buschur product page on buschursllc.com/br-cart/."""
    try:
        parsed = urlparse(url)
    except ValueError:
        return False
    host = (parsed.hostname or "").lower()
    if host not in ("buschursllc.com", "www.buschursllc.com"):
        return False
    return bool(_PRODUCT_PATH_RE.match(parsed.path or ""))


def _is_category_url(url: str) -> bool:
    """True if ``url`` is a Buschur category page (``/br-cart/<id>-<slug>``)."""
    try:
        parsed = urlparse(url)
    except ValueError:
        return False
    host = (parsed.hostname or "").lower()
    if host not in ("buschursllc.com", "www.buschursllc.com"):
        return False
    return bool(_CATEGORY_PATH_RE.match(parsed.path or ""))


def _discover_product_urls_via_categories() -> List[str]:
    """
    Walk the homepage's category menu to collect every category URL, then fetch
    each category page and harvest product URLs. No XML sitemap exists on this
    store. Categories are small enough (5-30 products each) that pagination
    doesn't matter — the default items-per-page fits the whole category.
    Dedupes on path. Returns an empty list on total network failure.
    """
    category_urls: List[str] = []
    seen_cats: set[str] = set()

    try:
        home_html = fetch_page(CART_ROOT, timeout=20)
    except Exception:
        return []

    home_soup = BeautifulSoup(home_html, "html.parser")
    for a in home_soup.find_all("a", href=True):
        if not isinstance(a, Tag):
            continue
        href = a.get("href")
        if not isinstance(href, str) or not href.strip():
            continue
        abs_url = urljoin(CART_ROOT, href.strip())
        if not _is_category_url(abs_url):
            continue
        # Normalize: strip trailing slash so "/12-evo-789" and "/12-evo-789/" dedupe.
        try:
            parsed = urlparse(abs_url)
        except ValueError:
            continue
        path = (parsed.path or "").rstrip("/")
        key = f"{parsed.hostname}{path}".lower()
        if key in seen_cats:
            continue
        seen_cats.add(key)
        category_urls.append(f"{parsed.scheme}://{parsed.hostname}{path}")

    if not category_urls:
        return []

    seen_products: set[str] = set()
    out: List[str] = []
    for i, cat_url in enumerate(category_urls):
        if i > 0:
            time.sleep(apply_delay_jitter(DEFAULT_REQUEST_DELAY_SEC))
        try:
            cat_html = fetch_page(cat_url, timeout=15)
        except Exception:
            continue
        cat_soup = BeautifulSoup(cat_html, "html.parser")
        for a in cat_soup.find_all("a", href=True):
            if not isinstance(a, Tag):
                continue
            href = a.get("href")
            if not isinstance(href, str) or not href.strip():
                continue
            abs_url = urljoin(cat_url + "/", href.strip())
            # Strip query (add-to-cart links use ?add=1&id_product=… — not product pages)
            base = abs_url.split("?", 1)[0]
            if not _is_product_url(base):
                continue
            try:
                parsed = urlparse(base)
            except ValueError:
                continue
            key = f"{parsed.hostname}{parsed.path}".lower()
            if key in seen_products:
                continue
            seen_products.add(key)
            out.append(base)

    return out


def _normalize_image_url(raw: str) -> Optional[str]:
    """Expand protocol-relative URLs; resolve bare paths against BUSCHUR_BASE."""
    s = raw.strip()
    if not s:
        return None
    if s.startswith("//"):
        return "https:" + s
    if s.startswith("/"):
        return BUSCHUR_BASE + s
    if s.startswith("http://"):
        return "https://" + s[len("http://") :]
    if not s.startswith("http"):
        return None
    return s


def _is_valid_product_image(url: str) -> bool:
    """Keep ``/br-cart/…/<name>.jpg`` product images; reject site chrome."""
    if not url or len(url) < 20:
        return False
    low = url.lower()
    if low.startswith("data:"):
        return False
    if "buschursllc.com" not in low:
        return False
    if re.search(r"logo|favicon|placeholder|sprite|banner|themes/theme|/modules/|/img/icons?/", low):
        return False
    return True


def _extract_gallery_images(soup: BeautifulSoup) -> List[str]:
    """
    Collect product image URLs. PrestaShop serves the hero at
    ``#image-block img`` (``tm_large_default`` size) and thumbnails at
    ``#thumbs_list_frame img`` (``tm_cart_default`` size) — same photo,
    different size. We prefer the large version and ignore the thumbs
    strip when the same filename already appears at large size.
    Capped at 12.
    """
    ordered: List[str] = []
    seen_stems: set[str] = set()

    def _stem(url: str) -> str:
        # Collapse the same photo at different PrestaShop sizes (tm_large_default
        # vs tm_cart_default). File name (last path segment, no query / size
        # directory) is the identity.
        base = url.split("?", 1)[0].rsplit("/", 1)[-1]
        return re.sub(r"\.(jpg|jpeg|png|webp|gif)$", "", base, flags=re.IGNORECASE).lower()

    def add(raw: Optional[str]) -> None:
        if not raw or len(ordered) >= 12:
            return
        normalized = _normalize_image_url(raw)
        if not normalized or not _is_valid_product_image(normalized):
            return
        stem = _stem(normalized)
        if stem and stem in seen_stems:
            return
        seen_stems.add(stem)
        ordered.append(normalized)

    # Primary: hero large image.
    for img in soup.select("#image-block img"):
        if isinstance(img, Tag):
            for attr in ("data-src", "src"):
                v = img.get(attr)
                if isinstance(v, str) and v.strip():
                    add(v)
                    break

    # Secondary: thumbnails (same photo, smaller size — collapsed via stem).
    for img in soup.select("#thumbs_list_frame img, #views_block img"):
        if isinstance(img, Tag):
            for attr in ("data-src", "src"):
                v = img.get(attr)
                if isinstance(v, str) and v.strip():
                    add(v)
                    break

    # OG image fallback.
    if not ordered:
        og = soup.find("meta", property="og:image")
        if isinstance(og, Tag):
            content = meta_content(og)
            if content:
                add(content)

    return ordered[:12]


def _extract_description(soup: BeautifulSoup) -> Optional[str]:
    """
    Description lives inside the product tab's ``<div class="rte">``. Often a
    single sentence on this storefront — keep it when non-trivial.
    """
    for sel in ("#short_description_content", ".rte", "#idTab1 .rte", "[itemprop='description']"):
        el = soup.select_one(sel)
        if not isinstance(el, Tag):
            continue
        text = el.get_text(separator=" ", strip=True)
        if text and len(text) > 10:
            return normalize_description_text(text, max_len=2000)
    og_desc = soup.find("meta", property="og:description")
    if isinstance(og_desc, Tag):
        d = meta_content(og_desc)
        if d and d.strip():
            return normalize_description_text(d, max_len=2000) or d.strip()[:2000]
    meta_desc = soup.find("meta", attrs={"name": "description"})
    if isinstance(meta_desc, Tag):
        d = meta_content(meta_desc)
        if d and d.strip():
            return normalize_description_text(d, max_len=2000) or d.strip()[:2000]
    return None


def _extract_name(soup: BeautifulSoup) -> Optional[str]:
    """
    Product name from ``<h1>`` first (PrestaShop renders it clean), then
    ``og:title`` with the ``" - Buschurs LLC"`` site suffix stripped.
    """
    h1 = soup.find("h1")
    if isinstance(h1, Tag):
        text = h1.get_text(strip=True)
        if text:
            return text
    og = soup.find("meta", property="og:title")
    if isinstance(og, Tag):
        content = meta_content(og)
        if content and content.strip():
            name = content.strip()
            # Strip " - Buschurs LLC" / " - Buschur Racing" trailing site name.
            name = re.sub(r"\s*-\s*Buschur(?:'s|s)?\s*(?:LLC|Racing)\s*$", "", name, flags=re.IGNORECASE)
            return name or None
    return None


def _extract_sku(soup: BeautifulSoup) -> Optional[str]:
    """
    ``<span itemprop="sku">…</span>`` inside ``#product_reference``. Often blank
    on this storefront — we intentionally return None in that case rather than
    invent a SKU.
    """
    el = soup.select_one('#product_reference [itemprop="sku"], [itemprop="sku"]')
    if isinstance(el, Tag):
        text = el.get_text(strip=True)
        if text:
            return text
    return None


class BuschurRacingAdapter(RetailerCrawlerAdapter):
    """
    Buschur Racing (``buschursllc.com/br-cart/``) adapter. Legacy PrestaShop
    storefront, plain HTTP works (no Cloudflare challenge). Discovery walks
    the homepage category menu → each category page collects product URLs
    (no XML sitemap exists). Parsing is microdata + OG-meta + DOM — the page
    has **no JSON-LD**.

    Brand strategy: hybrid pass-through.
    - Title heuristic → third-party manufacturer when the title leads with
      one (``JE``, ``Wiseco``, ``Tial``, …).
    - ``"Buschur Racing"`` house-brand coercion only when the title clearly
      identifies house origin (``Buschur's …``).
    - Car-make / Mitsubishi-DSM / Evo tokens are dropped so we don't mint a
      ``"Mitsubishi"`` or ``"Evo"`` manufacturer row next to real brands.
    - SKU suffix (``-JE``, ``-WIS``) is a last-resort hint when the other
      paths miss.

    SKUs are often blank (house-brand items). We keep the empty value as
    ``None``; cross-retailer dedupe will fall back to ``retailer + url`` on
    those rows, matching the ``radium`` approach.
    """

    ADAPTER_NAME: ClassVar[str] = "buschurracing"
    FETCHER_TIER = "http"

    def discover_product_urls(self) -> Iterator[str]:
        """Yield product URLs from the homepage category walk; env override wins."""
        for url in _resolve_start_urls():
            yield url

    def parse_product_page(self, html: str, url: str) -> Optional[ScrapedPayload]:
        """
        Parse a Buschur Racing product page into a ``ScrapedPayload``. Returns
        ``None`` when the URL isn't product-shaped or the page has no h1 / name.
        """
        if not _is_product_url(url):
            return None

        soup = BeautifulSoup(html, "html.parser")

        name = _extract_name(soup)
        if not name or len(name) < 3:
            return None

        # --- SKU (often blank on this storefront) -------------------------------
        sku_raw = _extract_sku(soup)
        part_number: Optional[str] = normalize_part_number(sku_raw) if sku_raw else None
        if not part_number:
            # Visible sku/part-number patterns in body text (cheap fallback).
            candidate = extract_sku_from_text(soup.get_text())
            if candidate:
                part_number = candidate
        if not part_number:
            # Title-derived part/model code (e.g. ``VF650``). Keeps blank SKUs
            # blank on most Buschur items — their titles rarely contain MPN-like
            # tokens — but recovers the odd page that does.
            part_number = normalize_part_number(extract_part_number_candidate_from_title(str(name)))

        # --- Price --------------------------------------------------------------
        # og:product:price:amount → DOM body regex via shared helper.
        price_cents = extract_dom_price(soup)

        # --- Description -------------------------------------------------------
        description = _extract_description(soup)

        # --- Brand cascade -----------------------------------------------------
        # No microdata brand / manufacturer on this storefront; lean on the
        # title heuristic, then house-brand check, then SKU suffix, then
        # description / fallback.
        part_manufacturer: Optional[str] = _normalize_part_manufacturer(part_manufacturer_from_title(str(name)))
        # House-brand coercion: title starts with ``Buschur`` / ``Buschurs`` /
        # ``Buschur's``. Never applied as a blanket default because that would
        # mis-label the JE / Wiseco / Tial items that share this store.
        if _HOUSE_BRAND_TITLE_RE.match(name or ""):
            part_manufacturer = _HOUSE_BRAND
        # SKU-suffix upgrade only when the other paths missed (low-signal).
        if not part_manufacturer:
            from_sku = _brand_from_sku_suffix(sku_raw)
            if from_sku:
                part_manufacturer = from_sku
        # Description-based hint (covers e.g. "CSF radiator" mentioned inline).
        if not part_manufacturer and description:
            part_manufacturer = _normalize_part_manufacturer(
                part_manufacturer_from_description(description, product_name=str(name))
            )
        # Shared known-pattern fallback (VF-Engineering and friends).
        if not part_manufacturer:
            part_manufacturer = _normalize_part_manufacturer(part_manufacturer_fallback_from_title(str(name)))

        # --- Images ------------------------------------------------------------
        image_urls = _extract_gallery_images(soup) or None

        return ScrapedPayload(
            name=str(name),
            product_url=url,
            description=description if description else None,
            price_cents=price_cents,
            part_manufacturer=part_manufacturer,
            part_number=part_number,
            image_urls=image_urls,
        )
