"""
Buschur Racing (``buschurracing.com`` → ``buschursllc.com/br-cart/``)
crawler adapter — Tier 0 (plain HTTP).

Buschur Racing is a long-running Evo / DSM specialist (1G/2G DSM, Evo 7/8/9/X,
a little 22+ Ford Maverick and Ralliart). Their catalog mixes **house-brand
hardware** (``Buschur's 1G DSM Turbo Back Exhaust``, ``Buschur's 90-94 AWD
DSM 3" Downpipe Back``) with **third-party resale** (JE forged pistons,
Wiseco HD pistons, Tial wastegates, etc.), so we follow the multi-brand
pass-through pattern from ``ind.py`` / ``corksport.py`` /
``modernmusclextreme.py`` — NOT the single-brand coerce pattern.

Hosts
-----
- ``buschurracing.com`` — marketing domain; 302s to the real storefront at
  ``http://buschursllc.com/br-cart/`` (then 301 to https). The TLS cert on
  ``buschurracing.com`` does not cover the SAN — Apache serves the default
  ``buschursllc.com`` cert — which trips ``curl`` without ``-k`` but
  ``requests`` follows redirects without issue since it lands on the valid
  cert for the final host.
- ``buschuracing.com`` — a typo-catcher single-letter domain; returns a
  near-empty 80-byte placeholder page, NOT the store. We list it in the
  host map so archive rescrape can recognize the URL, but all discovery
  and default start URLs point at ``buschursllc.com/br-cart/``.
- ``buschursllc.com/br-cart/`` — the actual storefront path. Everything
  lives under the ``/br-cart/`` prefix (the root ``/`` is a near-empty
  static page). The site is served by Apache 2.2.11 + PHP 7.4 — classic
  legacy-box shape, but no Cloudflare or other active bot challenge, and
  plain ``requests`` with a browser-ish UA returns HTTP 200 for robots,
  categories, and product pages. Tier 0 is correct.

Platform: **PrestaShop 1.6 / 1.7-era** (theme ``theme1005``). Telltales: the
``<meta name="generator" content="PrestaShop" />`` tag, the boilerplate
``# robots.txt automaticaly generated by PrestaShop e-commerce open-source
solution`` header, the ``/br-cart/<category-slug>/<id>-<slug>.html`` URL
shape, the ``#product_reference`` + ``#our_price_display`` +
``#short_description_content`` DOM ids, and the ``itemprop="sku"`` /
``itemprop="name"`` / ``itemprop="price"`` microdata with a
``<meta property="product:price:amount">`` OG extension.

Structured data shape
---------------------
**No JSON-LD.** The page emits schema.org data as **microdata** inside the
``#product_reference`` / ``#our_price_display`` / content blocks plus the
standard ``og:*`` + ``product:price:*`` OpenGraph meta. Concretely:

- ``<h1>`` / ``<meta property="og:title">`` — product name (site-suffixed
  ``" - Buschurs LLC"`` in og:title, so we prefer ``<h1>``).
- ``<span itemprop="sku">…</span>`` inside ``#product_reference``. **Often
  blank** — house-brand items and many third-party resales have no SKU at
  all on this store. When present, values look like ``10170-JE`` (JE
  pistons) or ``10171-WIS`` (Wiseco) — a Buschur internal code with the
  manufacturer as a short suffix.
- ``<meta property="product:price:amount" content="680">`` +
  ``<meta property="product:price:currency" content="USD">`` — parsed via
  the shared ``extract_dom_price`` helper (which reads
  ``product:price:amount`` before falling back to body regex).
- ``<div class="rte">…</div>`` inside the product tab — the editorial
  description. Often a single sentence on this store, which we keep when
  present.
- ``#image-block img[src]`` — hero image at ``tm_large_default`` size.
  Thumbnail strip at ``#thumbs_list_frame img[src]`` (``tm_cart_default``
  size). We keep the hero; thumbnails are the same photos at smaller
  resolution so we don't dedupe the gallery further — there simply is no
  multi-image gallery on most products.

**Brand is never present in the microdata** — there is no
``itemprop="brand"`` / ``itemprop="manufacturer"`` anywhere on the product
page, and the ``<meta property="product:brand">`` tag is absent. So brand
resolution is entirely title-heuristic + SKU-suffix hint + a small
house-brand detector.

Variant rule (per VARIANTS.md)
------------------------------
PrestaShop supports combinations via ``<select name="group_*">`` /
``#idCombination`` pickers, but Buschur's catalog **does not use them** on
the pages we sampled — the ``#idCombination`` block renders empty and there
is no variant JSON blob. Variant-like differences (bore oversizes for JE
pistons, pipe diameters for downpipes) appear to be handled offline ("Please
specify bore size when ordering" in the description text) rather than as
separate purchasable SKUs. One ``ScrapedPayload`` per product URL matches
the current model with no lossy pick — this is the invisible-variant case
where the parent page IS the only URL.

Brand strategy: **hybrid pass-through**
---------------------------------------
1. Title heuristic via ``part_manufacturer_from_title`` first (returns e.g.
   ``"JE"`` / ``"Wiseco"`` / ``"Tial"`` for third-party products).
2. House-brand coercion to ``"Buschur Racing"`` when ANY of:
   - the title leads with ``"Buschur"`` / ``"Buschurs"`` / ``"Buschur's"``
     (``'s`` handled case-insensitively; the storefront spells it both ways);
   - the title heuristic picked a car-make / Mitsubishi / Evo / DSM token
     that is clearly NOT the manufacturer. The blocklist covers the
     Mitsubishi-DSM surface: ``mitsubishi``, ``evo``, ``evolution``,
     ``lancer``, ``eclipse``, ``ralliart``, ``galant``, ``dsm`` (+ ``1g``/``2g``
     abbreviations used as title leaders), plus the generic makes that
     could show up in cross-platform kits.
3. If (1) returned a blocklisted / car-make token AND neither the title nor
   the URL indicate house-brand, drop to ``None`` so ingest stores
   ``part_manufacturer_id = NULL`` rather than creating a ``"Mitsubishi"``
   or ``"Evo"`` manufacturer row alongside real brands. Multi-brand
   pass-through — we NEVER blanket-coerce a non-house product to ``"Buschur Racing"``.
4. As a final hint, the SKU suffix (``10170-JE`` → JE, ``10171-WIS`` →
   Wiseco) can upgrade a missing brand; this is a weak signal (the suffix
   is short and ambiguous) so we only map a small known-suffix set.

Discovery
---------
**No XML sitemap.** ``/sitemap.xml``, ``/br-cart/sitemap.xml``, and the
PrestaShop module's conventional ``/1_en_0_sitemap.xml`` all return 404.
The site exposes an HTML "Sitemap" page at ``/br-cart/sitemap`` but it's
just a lightweight page-map, not a product list. We walk the homepage's
left-rail category menu (~211 ``/br-cart/<id>-<slug>`` links covering
the Evo / DSM / Ford / Ralliart trees), then fetch each leaf category
page and collect ``/br-cart/<category-slug>/<id>-<product-slug>.html``
product URLs from it. Categories are small (often 5-30 products each),
so pagination doesn't matter; the default ``n=`` items-per-page value
fits the whole category on one screen. Results are deduplicated on
path. ``CRAWLER_BUSCHURRACING_START_URLS`` (comma-separated) overrides
the discovery with a fixed URL list for smoke tests or targeted re-runs.

Tier rationale
--------------
Plain HTTP works end to end. ``/robots.txt`` and product pages both return
200 to a plain ``Mozilla/5.0`` UA; there is no Cloudflare / Sucuri / JS
challenge. The TLS fingerprint mismatch on the marketing domain
(``buschurracing.com`` not on the cert) is handled by letting ``requests``
follow redirects to the real host, so we don't need Tier 1 impersonation
either.

Caveats
-------
- **Blank SKUs dominate.** Many house-brand items have no
  ``itemprop="sku"`` value. Cross-retailer dedupe will fall back to
  ``retailer + url`` on those rows, same as ``radium``. Do not treat the
  blanks as a scrape failure — they reflect the site's data.
- **Apache 2.2.11 is end-of-life** (released 2009). Occasional 500s or
  connection drops on odd URLs are plausible; the shared retry loop in
  ``fetch_with_retries`` handles transient failures.
- **``buschurracing.com`` SAN mismatch.** The cert CN is
  ``buschursllc.com`` and ``buschurracing.com`` is NOT in the SAN. Python
  ``requests`` follows the 302 to the real host before the final TLS
  handshake (per redirect + connection pool semantics), so verification
  succeeds; bare ``curl`` on the marketing domain needs ``-k`` or to
  target the final host directly.
- **Legacy prices.** The OG ``product:price:amount`` values are integer
  dollar amounts (``"680"`` not ``"680.00"``). ``parse_price_cents`` reads
  those as ``68000`` cents correctly (integer → float → ×100).
"""

